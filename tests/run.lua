vim.opt.rtp:prepend(vim.fn.getcwd())
vim.o.swapfile = false
vim.g.mapleader = ' '
local wizard, config, runner = require('wizard'), require('wizard.config'), require('wizard.runner')
local api = vim.api
local total = 0
local function eq(a, b, label)
  total = total + 1
  assert(vim.deep_equal(a, b), (label or 'assertion') .. ': ' .. vim.inspect(a) .. ' ~= ' .. vim.inspect(b))
end
local function wait_for(fn)
  assert(vim.wait(5000, fn, 10), 'async operation timed out')
end
local function read(p) return table.concat(vim.fn.readfile(p), '\n') end
local root = vim.fn.tempname()
vim.fn.mkdir(root .. '/nested', 'p')
vim.env.WIZARD_CAPTURE = root .. '/capture.json'
local notices = {}
vim.notify = function(msg) notices[#notices + 1] = msg end
local portfile = root .. '/port'
local server = vim.system({'python3', vim.fn.getcwd() .. '/tests/http-server.py', portfile, root .. '/capture.json'})
wait_for(function() return vim.fn.filereadable(portfile)==1 end)
local base_url = 'http://127.0.0.1:' .. read(portfile)
local presets = {
  {name='small', model='small:20b', request={options={num_ctx=65536}}},
  {name='large', model='large'},
}
local opts = {presets=presets,defaults={api='ollama',base_url=base_url}}
local function setup() wizard.setup(opts) end
local function open()
  vim.cmd('enew!')
  vim.cmd('file ' .. vim.fn.fnameescape(root .. '/nested/file.lua'))
  api.nvim_buf_set_lines(0,0,-1,false,{'return 1'})
  vim.cmd('write!')
  return api.nvim_get_current_buf()
end
local function run(prompt)
  wizard.prompt(); vim.cmd('stopinsert'); wizard.submit(prompt)
  wait_for(function() return not wizard.status() or not wizard.status().process end)
end
local function capture() return vim.json.decode(read(vim.env.WIZARD_CAPTURE)) end
local function tests()
  wizard.setup()
  local ok, err=pcall(config.resolve,root..'/nested/file.lua')
  eq(ok,false,'empty presets rejected'); assert(err:find('No model presets'))
  setup()
  local ctx=config.resolve(root..'/nested/file.lua')
  eq(ctx.index,1,'first preset default')
  config.select(ctx,2); eq(config.resolve(root..'/nested/file.lua').index,2,'selection persists')
  local c=config.effective(ctx)
  eq(c.request.options.num_ctx,65536,'provider options preserved')
  eq(c.base_url,base_url,'shared base URL')
  local req=runner.build(ctx,'return 1\n','/secret/project/index.lua','change')
  eq(req.body.messages[2].content,'File: index.lua\n\n```\nreturn 1\n```\n\nRequested change:\nchange','exact prompt, no extra newline or full path')
  local custom=vim.deepcopy(ctx);custom.presets[custom.index].request={tools={{name='bad'}},format='json',messages={{content='other context'}}}
  local clean=runner.build(custom,'return 1','file.lua','change')
  eq(clean.body.tools,nil,'tools blocked even through request overrides')
  eq(clean.body.format,nil,'schema output blocked through request overrides')
  eq(#clean.body.messages,2,'context override blocked')
  eq(runner.decode('ollama',{message={content='',thinking='reasoning'}}),nil,'reasoning-only response rejected')
  eq(runner.decode('openai',{choices={{message={content='x',tool_calls={{}}}}}}),nil,'protocol tool call rejected')
  eq(runner.decode('responses',{status='incomplete'}),nil,'incomplete Responses output rejected')
  local normalize=require('wizard.output').normalize
  eq(normalize('```tsx\n<button />\n```\n','index.ts',''),'<button />\n','language fence removed')
  eq(normalize('~~~\nreturn 2\n~~~','test.lua',''),'return 2\n','tilde fence removed')
  eq(normalize('```lua\nreturn 2\n```\n','README.md',''),'```lua\nreturn 2\n```\n','Markdown preserved')
  eq(normalize('```\ntext\n```','file.txt','',false),'```\ntext\n```','fence opt out')
  eq(normalize('```js\ncode','file.ts',''),nil,'unclosed fence rejected')
  eq(normalize('{"name":"edit_file","arguments":{}}','index.ts',''),nil,'tool envelope rejected')
  eq(normalize('{"name":"edit_file","arguments":{}}','data.json',''),'{"name":"edit_file","arguments":{}}','JSON document preserved')
  vim.fn.writefile({vim.json.encode({presets={{model='project'}},defaults={base_url=base_url,api='openai'}})},root..'/nvim-wizard.json')
  ctx=config.resolve(root..'/nested/file.lua');eq(ctx.presets[1].model,'project','nearest project config')
  eq(config.effective(ctx).api,'openai','project defaults override')
  vim.fn.writefile({'{invalid'},root..'/nvim-wizard.json')
  eq(pcall(config.resolve,root..'/nested/file.lua'),false,'invalid JSON rejected')
  vim.fn.writefile({'{"presets":[]}'},root..'/nvim-wizard.json')
  eq(pcall(config.resolve,root..'/nested/file.lua'),false,'empty project list replaces global')
  vim.fn.writefile({'{"codex":{}}'},root..'/nvim-wizard.json')
  eq(pcall(config.resolve,root..'/nested/file.lua'),false,'old Codex config rejected with migration error')
  vim.fn.delete(root..'/nvim-wizard.json'); setup()
  local source=open()
  local function press(key, mode)
    local map=vim.fn.maparg(key,mode or 'n',false,true)
    assert(type(map.callback)=='function','No callback for '..key)
    map.callback()
  end
  eq(vim.fn.maparg('<CR>','n',false,true).buffer,1,'Enter is buffer-local')
  press('<CR>');vim.cmd('stopinsert')
  eq(wizard.status().prompt_win~=nil,true,'Enter opens prompt')
  eq(vim.fn.maparg('<S-CR>','i',false,true).rhs,'<C-o>o','Shift Enter keeps multiline prompt editing')
  press('<Esc>');eq(wizard.status(),nil,'Escape closes prompt')
  press('<S-CR>');press('2')
  eq(config.resolve(root..'/nested/file.lua').index,2,'Shift Enter opens numeric selector')
  local ordinary=api.nvim_create_buf(false,true)
  api.nvim_set_current_buf(ordinary)
  eq(vim.fn.maparg('<CR>','n'),'', 'special buffers keep Enter')
  eq(vim.fn.maparg('<S-CR>','n'),'', 'special buffers keep Shift Enter')
  api.nvim_set_current_buf(source)
  vim.bo[source].readonly=true
  eq(vim.fn.maparg('<CR>','n'),'', 'readonly files keep Enter')
  vim.bo[source].readonly=false
  -- A request temporarily borrows Esc and restores an existing mapping.
  local escaped=0
  vim.keymap.set('n','<Esc>',function() escaped=escaped+1 end,{buffer=source})
  press('<CR>');vim.cmd('stopinsert');wizard.submit('[slow]')
  press('<CR>');eq(wizard.status().prompt_win,nil,'Enter does nothing while running')
  press('<Esc>');eq(wizard.status(),nil,'Escape cancels running request')
  press('<Esc>');eq(escaped,1,'existing Escape mapping restored')
  run('change')
  local proposal=wizard.status().preview_buf
  eq(vim.fn.maparg('<CR>','i'),'', 'proposal insert Enter remains native')
  eq(vim.fn.maparg('<Esc>','i'),'', 'proposal insert Escape remains native')
  api.nvim_feedkeys(api.nvim_replace_termcodes('i<CR><Esc>',true,true,true),'xt',false)
  eq(wizard.status()~=nil,true,'one Escape from insert preserves review')
  eq(#api.nvim_buf_get_lines(proposal,0,-1,false),2,'insert Enter adds newline')
  press('<Esc>');eq(wizard.status(),nil,'second Escape discards review')
  run('change');press('<CR>')
  eq(read(root..'/nested/file.lua'),'return 2','review Enter accepts and saves')
  eq(wizard.status(),nil,'review Enter closes session')
  api.nvim_buf_set_lines(source,0,-1,false,{'return 1'});vim.cmd('write!')
  wizard.models()
  local buf=api.nvim_get_current_buf()
  eq(#api.nvim_buf_get_lines(buf,0,-1,false),2,'selector rows')
  local maps=api.nvim_buf_get_keymap(buf,'n')
  for _, m in ipairs(maps) do if m.lhs=='2' then m.callback() end end
  eq(config.resolve(root..'/nested/file.lua').index,2,'numeric selection')
  setup()
  run('change to 2; $(never_execute) `never_execute`')
  local s=wizard.status();assert(s and s.preview_buf)
  eq(read(s.path),'return 1','disk untouched before acceptance')
  eq(api.nvim_buf_get_lines(source,0,-1,false),{'return 1'},'source untouched before acceptance')
  eq(api.nvim_buf_get_lines(s.preview_buf,0,-1,false),{'return 2'},'result shown')
  eq(capture().path,'/api/chat','native Ollama endpoint')
  eq(capture().body.messages[2].content:find('$(never_execute)',1,true)~=nil,true,'prompt supplied literally')
  eq(#capture().body.messages,2,'only system and current file request supplied')
  eq(capture().body.tools,nil,'no tools sent')
  eq(capture().body.format,nil,'no structured output sent')
  eq(capture().body.stream,false,'nonstreaming request')
  eq(capture().body.model,'small:20b','selected model sent')
  eq(capture().body.options.num_ctx,65536,'model options sent')
  wizard.prompt();vim.cmd('stopinsert');wizard.submit('[refine]')
  wait_for(function() return not wizard.status().process end)
  eq(api.nvim_buf_get_lines(s.original_buf,0,-1,false),{'return 1'},'original fixed across refinements')
  eq(api.nvim_buf_get_lines(s.preview_buf,0,-1,false),{'return 3'},'latest refinement')
  eq(capture().body.messages[2].content:find('return 2',1,true)~=nil,true,'refinement receives latest proposal')
  api.nvim_buf_set_lines(s.preview_buf,0,-1,false,{'return 4'})
  wizard.accept();eq(read(root..'/nested/file.lua'),'return 4','manual proposal edits saved')
  eq(wizard.status(),nil,'accept cleans session')
  api.nvim_buf_set_lines(source,0,-1,false,{'return 1'});vim.cmd('write!')
  run('change');wizard.cancel()
  eq(read(root..'/nested/file.lua'),'return 1','cancel preserves disk')
  eq(api.nvim_get_current_buf(),source,'cancel returns to source')
  run('change');vim.fn.writefile({'external edit'},root..'/nested/file.lua');wizard.accept()
  eq(wizard.status()~=nil,true,'disk conflict blocks acceptance');wizard.cancel()
  vim.fn.writefile({'return 1'},root..'/nested/file.lua')
  run('change');api.nvim_buf_set_lines(source,0,-1,false,{'external buffer edit'});wizard.accept()
  eq(wizard.status()~=nil,true,'buffer conflict blocks acceptance');wizard.cancel()
  api.nvim_buf_set_lines(source,0,-1,false,{'return 1'})
  run('[fail]');eq(wizard.status(),nil,'failed process cleans session')
  eq(notices[#notices]:find('fixture provider failure',1,true)~=nil,true,'HTTP error reported')
  run('[missing]');eq(wizard.status(),nil,'missing response rejected')
  run('[empty]');eq(api.nvim_buf_get_lines(wizard.status().preview_buf,0,-1,false),{''},'empty file supported');wizard.cancel()
  wizard.prompt();vim.cmd('stopinsert');wizard.submit('[slow]');wizard.cancel()
  eq(wizard.status(),nil,'running request cancelled')
  opts.timeout_ms=100;setup();run('[slow]');eq(wizard.status(),nil,'timeout cleans session')
  opts.timeout_ms=nil;setup()
  wizard.prompt();vim.cmd('stopinsert')
  local pb=api.nvim_get_current_buf()
  for _, m in ipairs(api.nvim_buf_get_keymap(pb,'n')) do if m.lhs=='<Esc>' then m.callback() end end
  eq(wizard.status(),nil,'Escape dismisses prompt')
  run('[fenced]'); eq(api.nvim_buf_get_lines(wizard.status().preview_buf,0,-1,false),{'return 2'},'fences removed before preview'); wizard.cancel()
  run('[toolcall]'); eq(wizard.status(),nil,'tool calls rejected before preview')
  eq(notices[#notices]:find('tool call instead of file contents',1,true)~=nil,true,'tool call error reported')
  run('[bad-json]');eq(wizard.status(),nil,'invalid JSON rejected')
  run('[truncated]');eq(wizard.status(),nil,'truncated output rejected')
  run('[redirect]');eq(wizard.status(),nil,'HTTP redirects rejected')
  opts.defaults.api='openai';setup();run('change')
  eq(capture().path,'/chat/completions','OpenAI-compatible endpoint')
  wizard.cancel()
  opts.defaults.api='responses';setup();run('change')
  eq(capture().path,'/responses','Responses-compatible endpoint')
  eq(capture().body.store,false,'Responses storage disabled')
  eq(capture().body.messages,nil,'Responses uses input')
  wizard.cancel(); opts.defaults.api='ollama';setup()
  vim.env.WIZARD_TEST_KEY='fixture-key'
  opts.defaults.api_key_env='WIZARD_TEST_KEY'; setup();run('change')
  eq(capture().headers.Authorization,'Bearer fixture-key','environment authentication')
  wizard.cancel();opts.defaults.api_key_env=nil;setup()
  opts.curl='/no-such-curl';setup();run('change');eq(wizard.status(),nil,'spawn failure cleans session');opts.curl=nil;setup()
  opts.defaults.api_key_env='WIZARD_NO_SUCH_KEY';setup();run('change');eq(wizard.status(),nil,'missing credentials clean session');opts.defaults.api_key_env=nil;setup()
  -- Unsaved input is the snapshot and must survive a discarded proposal.
  api.nvim_buf_set_lines(source,0,-1,false,{'unsaved change'})
  run('change')
  eq(api.nvim_buf_get_lines(wizard.status().original_buf,0,-1,false),{'unsaved change'},'unsaved snapshot')
  eq(capture().body.messages[2].content:find('unsaved change',1,true)~=nil,true,'unsaved text supplied to provider')
  wizard.cancel()
  eq(api.nvim_buf_get_lines(source,0,-1,false),{'unsaved change'},'cancel keeps unsaved text')
  eq(vim.bo[source].modified,true,'cancel keeps modified flag')
  api.nvim_buf_set_lines(source,0,-1,false,{'return 1'})
  vim.bo[source].fileformat='dos'
  vim.cmd('write!')
  run('change')
  eq(vim.bo[wizard.status().preview_buf].fileformat,'dos','CRLF format preserved')
  wizard.accept()
  local f=assert(io.open(root..'/nested/file.lua','rb'));local bytes=f:read('*a');f:close()
  eq(bytes,'return 2\r\n','CRLF disk write')
  vim.bo[source].fileformat='unix';vim.bo[source].endofline=false;vim.bo[source].fixendofline=false
  api.nvim_buf_set_lines(source,0,-1,false,{'return 1'});vim.cmd('write!')
  run('change')
  eq(vim.bo[wizard.status().original_buf].endofline,false,'missing final newline snapshot')
  wizard.cancel()
  vim.bo[source].endofline=true;vim.cmd('write!')
  run('change')
  vim.cmd('tabclose!')
  wait_for(function() return wizard.status()==nil end)
  eq(api.nvim_get_current_buf(),source,'closing review tab discards')
  run('change')
  local write_error=api.nvim_create_autocmd('BufWritePre',{buffer=source,callback=function() error('simulated write error') end})
  wizard.accept()
  eq(wizard.status()~=nil,true,'write failure retains proposal')
  eq(api.nvim_buf_get_lines(source,0,-1,false),{'return 1'},'write failure restores source')
  api.nvim_del_autocmd(write_error);wizard.cancel()
  -- Multi-digit numbers use fixed width, so 01 and 10 never conflict.
  local many={}
  for i=1,12 do many[i]={model='m'..i} end
  wizard.setup({presets=many,defaults={base_url=base_url}});wizard.models()
  local mb=api.nvim_get_current_buf()
  for _, m in ipairs(api.nvim_buf_get_keymap(mb,'n')) do if m.lhs=='12' then m.callback() end end
  eq(config.resolve(root..'/nested/file.lua').index,12,'more than nine presets')
end
